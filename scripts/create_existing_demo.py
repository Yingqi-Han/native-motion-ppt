#!/usr/bin/env python3
"""Create a repo-authored existing-PPT regression; all content/data is simulated."""
import argparse
import io
import json
from pathlib import Path
from PIL import Image, ImageDraw
from pptx import Presentation
from native_motion.model import normalize
from native_motion.pptx_export import build, UNIT


def text(ident, content, box, size=30, **extra):
    return {'id':ident, 'kind':'text', 'text':content, 'box':box, 'size':size, 'fill':'173330', **extra}


def chrome(number, headline):
    return [text('section-'+str(number), 'EXISTING PPT / SIMULATED REGRESSION', [108,62,1180,42], 22, font='Space Grotesk SemiBold'),
            text('page-'+str(number), f'{number:02} / 03', [1330,62,170,42], 22, align='right', font='Space Grotesk SemiBold'),
            text('title-'+str(number), headline, [108,178,1380,110], 64, font='Noto Serif CJK SC', role='title'),
            text('footer-'+str(number), '仓库自制模拟样本：用于验证现成 PPT 增强，不代表客户业务内容。', [108,844,1380,36], 21, role='caption')]


def document():
    first = chrome(1, '把同一个论点，一起展开。')
    first += [text('intro-1','先保留页面上下文，再按两个信息块展开。',[112,310,1350,55],30)]
    for i,(heading,body) in enumerate([('保留现有版式','标题、文字、图片和备注\n继续留在原文件结构里。'),('按内容块出现','背景、论点与说明\n属于同一次点击。')]):
        x=108+i*720
        first += [{'id':f'card-{i}','kind':'rect','box':[x,420,660,330],'fill':'FFFFFF','radius':12},
                  text(f'argument-{i}',heading,[x+38,474,580,65],42),text(f'evidence-{i}',body,[x+38,590,580,110],31)]
    # All chart marks/labels are children of one native group.
    chart=[{'id':'chart-axis','kind':'line','box':[50,270,560,1],'stroke':'526763','stroke_width':2},
           text('chart-label','模拟完成度（%）',[50,0,570,45],27)]
    for i,(name,value) in enumerate([('方案 A',60),('方案 B',35)]):
        x=150+i*230
        chart += [{'id':f'bar-{i}','kind':'rect','box':[x,270-value*3,95,value*3],'fill':'00766A' if i==0 else 'B35735'},
                  text(f'value-{i}',str(value),[x-10,225-value*3,115,42],28,align='center'),
                  text(f'label-{i}',name,[x-20,295,140,45],25,align='center')]
    second=chrome(2,'图表与说明，保持关联。')+[text('intro-2','图表作为一个原生组合出现，图片与说明一起出现。',[112,310,1380,55],30),
        {'id':'chart-group','kind':'group','box':[135,410,650,350],'objects':chart},
        text('picture-caption','保留原始图片字节\n只给原生对象添加淡入。',[945,630,500,100],30)]
    third=chrome(3,'已有动画，按原样保留。')+[text('intro-3','这一页含原有运动与点击入场，增强时整页跳过。',[112,320,1380,60],30),
        {'id':'existing-token','kind':'ellipse','box':[160,500,150,150],'fill':'4460DA',
         'animations':[{'kind':'move','at':500,'duration':1800,'to':[65,0]}]},
        text('existing-click','原来的第一次点击，仍然有效。',[520,535,850,100],42,
             animations=[{'kind':'enter','click':1,'duration':650,'from':[0,0]}])]
    slides=[]
    for i,objects in enumerate([first,second,third],1):
        slides.append({'id':'existing-'+str(i),'duration':6500,'clicks':[1000] if i==3 else [],'background':'F4F2EA',
                       'transition':{'kind':'fade','duration':350},'objects':objects,
                       'notes':'SIMULATED REGRESSION. Preserve these speaker notes and original animation. Slide '+str(i)})
    return {'version':1,'title':'现有 PPT 增强 · 仓库自制模拟回归','canvas':{'width':1600,'height':900,'fps':30},
            'theme':{'font':'Noto Sans CJK SC','latin_font':'Space Grotesk SemiBold','background':'F4F2EA','foreground':'173330'},'slides':slides}


def create(destination):
    destination=Path(destination)
    if destination.exists() or destination.with_suffix('.source.json').exists():
        raise ValueError('Choose a new fixture output; existing files were preserved')
    doc=document();destination.parent.mkdir(parents=True,exist_ok=True);build(normalize(doc),destination)
    image=Image.new('RGB',(240,180),'#FFFFFF');draw=ImageDraw.Draw(image)
    draw.rounded_rectangle((25,25,215,155),radius=22,fill='#4460DA');draw.ellipse((85,55,155,125),fill='#F4F2EA')
    stream=io.BytesIO();image.save(stream,format='PNG');stream.seek(0)
    prs=Presentation(destination);picture=prs.slides[1].shapes.add_picture(stream,round(1090*UNIT),round(420*UNIT),round(240*UNIT),round(180*UNIT));picture.name='original-picture'
    prs.save(destination)
    destination.with_suffix('.source.json').write_text(json.dumps(doc,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    return {'pptx':str(destination),'scope':'Repository-authored simulated fixture; JSON describes native authored objects, extra picture generated by this script'}


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--out',required=True)
    print(json.dumps(create(p.parse_args().out),ensure_ascii=False,indent=2))
